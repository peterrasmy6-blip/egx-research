def compare(db, tickers: list[str]) -> dict:
    """
    Compare several companies across the same measures.

    Reports differences and says which company leads on each measure. It does
    NOT name an overall winner or suggest what to buy: which measures matter
    depends on the reader's own goals, and ranking them for the reader would be
    advice rather than research.
    """
    if len(tickers) < 2:
        raise ValueError("Choose at least two companies to compare.")
    if len(tickers) > 6:
        raise ValueError("Compare at most six companies at a time.")

    rows = []
    for t in tickers:
        r = db.execute(
            select(Security, SecurityMetrics)
            .join(SecurityMetrics, SecurityMetrics.security_id == Security.id)
            .where(Security.ticker == t.upper())).first()
        if r is None:
            raise ValueError("We do not hold data for '%s'." % t)
        rows.append(_row(r[0], r[1]))

    # (field, label, higher_is_better, unit)
    measures = [
        ("price", "Price", None, "EGP"),
        ("market_cap", "Market value", None, "EGP"),
        ("pe", "Price / earnings", False, "x"),
        ("pb", "Price / book", False, "x"),
        ("ev_ebitda", "EV / EBITDA", False, "x"),
        ("dividend_yield_pct", "Dividend yield", True, "%"),
        ("roe_pct", "Return on equity", True, "%"),
        ("roic_pct", "Return on invested capital", True, "%"),
        ("net_margin_pct", "Net margin", True, "%"),
        ("revenue_growth_pct", "Revenue growth", True, "%"),
        ("earnings_growth_pct", "Profit growth", True, "%"),
        ("debt_to_equity", "Debt / equity", False, "x"),
        ("volatility_pct", "Volatility", False, "%"),
        ("max_drawdown_pct", "Worst fall", True, "%"),
        ("ret_1y", "1-year return", True, "%"),
        ("ret_3y", "3-year return", True, "%"),
    ]

    table, observations = [], []
    for field, label, higher_better, unit in measures:
        vals = [(r["ticker"], r.get(field)) for r in rows]
        present = [(t, v) for t, v in vals if v is not None]
        leader = None
        if higher_better is not None and len(present) >= 2:
            leader = (max(present, key=lambda x: x[1])[0] if higher_better
                      else min(present, key=lambda x: x[1])[0])
        table.append({
            "field": field, "label": label, "unit": unit,
            "values": {t: v for t, v in vals},
            "leader": leader,
            "missing": [t for t, v in vals if v is None],
        })

    # A few plain-language observations, strictly factual.
    def _note(field, label, higher_better, fmt):
        present = [(r["ticker"], r.get(field)) for r in rows if r.get(field) is not None]
        if len(present) < 2:
            return
        best = (max(present, key=lambda x: x[1]) if higher_better
                else min(present, key=lambda x: x[1]))
        worst = (min(present, key=lambda x: x[1]) if higher_better
                 else max(present, key=lambda x: x[1]))
        if best[0] != worst[0]:
            observations.append(
                "%s: %s is at %s, against %s for %s."
                % (label, best[0], fmt % best[1], fmt % worst[1], worst[0]))

    _note("roe_pct", "Return on equity", True, "%.1f%%")
    _note("pe", "Price to earnings", False, "%.1fx")
    _note("dividend_yield_pct", "Dividend yield", True, "%.2f%%")
    _note("volatility_pct", "Volatility", False, "%.1f%%")
    _note("revenue_growth_pct", "Revenue growth", True, "%.1f%%")

    return {
        "companies": rows,
        "table": table,
        "observations": observations,
        "note": ("Leading on one measure does not make a company a better "
                 "investment. Which measures matter depends on what you are "
                 "trying to achieve, and that judgement is yours."),
    }
